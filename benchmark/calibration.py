def _percentile(values: Sequence[float], q: float) -> float | None:
    """Nearest-rank percentile (q in [0, 100]); None for an empty sample."""
    if not values:
        return None
    ordered = sorted(values)
    rank = max(1, math.ceil(q / 100 * len(ordered)))
    return ordered[min(rank, len(ordered)) - 1]


@dataclass(frozen=True)
class VariantSummary:
    run_id: str
    algorithm: str
    params: Mapping[str, int]
    budget: Mapping[str, Any]
    scheduled: int
    statuses: Mapping[str, int]
    limit_hits: Mapping[str, int]
    solve_seconds: Mapping[str, float | None]  # p50 / p95 / max / total
    quotes: Mapping[str, float | None]  # p50 / p95 / max
    compared: int  # ok cases with a positive best-known gross
    at_best: int
    shortfall_bps: Mapping[str, float | None]  # mean / p50 / p95 / max

    def to_dict(self) -> dict[str, Any]:
        return {
            "run_id": self.run_id,
            "algorithm": self.algorithm,
            "params": dict(self.params),
            "budget": dict(self.budget),
            "scheduled": self.scheduled,
            "statuses": dict(self.statuses),
            "limit_hits": dict(self.limit_hits),
            "solve_seconds": dict(self.solve_seconds),
            "quotes": dict(self.quotes),
            "compared": self.compared,
            "at_best": self.at_best,
            "shortfall_bps": dict(self.shortfall_bps),
        }


def _gross(record: Mapping[str, Any]) -> int | None:
    if record.get("status") != "ok":
        return None
    evaluation = record.get("evaluation") or {}
    value = evaluation.get("gross_output") if isinstance(evaluation, dict) else None
    return int(value) if value is not None else None


def _solve_seconds(record: Mapping[str, Any]) -> float | None:
    samples = (record.get("measurement") or {}).get("solve_seconds") or []
    if not samples:
        return None
    ordered = sorted(float(s) for s in samples)
    return ordered[len(ordered) // 2]


def summarize_runs(run_dirs: Iterable[str | Path]) -> list[VariantSummary]:
    """Per (run, algorithm) summaries over complete runs of one bundle."""
    loaded = []
    for run_dir in run_dirs:
        manifest = load_manifest(run_dir)
        loaded.append((manifest, load_case_records(run_dir)))
    if not loaded:
        raise CalibrationError("no runs given")
    hashes = {m.bundle_hash for m, _ in loaded}
    if len(hashes) != 1:
        raise CalibrationError(f"runs span {len(hashes)} bundles; compare one bundle only")
    objectives = {str(m.resolved_profile.get("objective", {}).get("mode")) for m, _ in loaded}
    if len(objectives) != 1:
        raise CalibrationError(f"runs mix objectives {sorted(objectives)}")
    best: dict[str, int] = {}
    for _, records in loaded:
        for record in records:
            gross = _gross(record)
            if gross is not None:
                case_id = str(record["case_id"])
                best[case_id] = max(best.get(case_id, gross), gross)
    summaries: list[VariantSummary] = []
    for manifest, records in loaded:
        profile = manifest.resolved_profile
        for algorithm in manifest.algorithms:
            rows = [r for r in records if r["algorithm"] == algorithm]
            times = [t for t in (_solve_seconds(r) for r in rows) if t is not None]
            quotes = [
                float(r["quotes"]["attempted"])
                for r in rows
                if isinstance(r.get("quotes"), dict) and r["quotes"].get("attempted") is not None
            ]
            shortfalls: list[float] = []
            at_best = 0
            for r in rows:
                gross = _gross(r)
                top = best.get(str(r["case_id"]))
                if gross is None or not top:
                    continue
                gap = float(Fraction(top - gross, top) * 10_000)
                shortfalls.append(gap)
                at_best += gross == top
            params = profile.get("algorithm_config", {}).get(algorithm, {}).get("params", {})
            summaries.append(
                VariantSummary(
                    run_id=manifest.run_id,
                    algorithm=algorithm,
                    params=dict(params),
                    budget=dict(profile.get("budget", {})),
                    scheduled=len(rows),
                    statuses=dict(Counter(str(r["status"]) for r in rows)),
                    limit_hits=dict(Counter(str(r["limit_hit"]) for r in rows if r["limit_hit"])),
                    solve_seconds={
                        "p50": _percentile(times, 50),
                        "p95": _percentile(times, 95),
                        "max": max(times) if times else None,
                        "total": sum(times) if times else None,
                    },
                    quotes={
                        "p50": _percentile(quotes, 50),
                        "p95": _percentile(quotes, 95),
                        "max": max(quotes) if quotes else None,
                    },
                    compared=len(shortfalls),
                    at_best=at_best,
                    shortfall_bps={
                        "mean": sum(shortfalls) / len(shortfalls) if shortfalls else None,
                        "p50": _percentile(shortfalls, 50),
                        "p95": _percentile(shortfalls, 95),
                        "max": max(shortfalls) if shortfalls else None,
                    },
                )
            )
    return summaries


def _fmt(value: float | None, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def summary_table(summaries: Sequence[VariantSummary]) -> list[str]:
    """Plain-text table (one line per run x algorithm) for stdout / the evidence doc."""
    header = (
        "| run | algorithm | params | ok/scheduled | other statuses | limit hits | "
        "solve p50/p95/max s | quotes p50/p95/max | at best | shortfall bps mean/p50/p95/max |"
    )
    lines = [header, "| " + " | ".join(["---"] * 10) + " |"]
    for s in summaries:
        others = ", ".join(f"{k} {v}" for k, v in sorted(s.statuses.items()) if k != "ok") or "-"
        hits = ", ".join(f"{k} {v}" for k, v in sorted(s.limit_hits.items())) or "-"
        params = " ".join(f"{k}={v}" for k, v in sorted(s.params.items())) or "-"
        lines.append(
            f"| {s.run_id} | {s.algorithm} | {params} | {s.statuses.get('ok', 0)}/{s.scheduled} "
            f"| {others} | {hits} | {_fmt(s.solve_seconds['p50'])}/"
            f"{_fmt(s.solve_seconds['p95'])}/{_fmt(s.solve_seconds['max'])} | "
            f"{_fmt(s.quotes['p50'], 0)}/{_fmt(s.quotes['p95'], 0)}/{_fmt(s.quotes['max'], 0)} | "
            f"{s.at_best}/{s.compared} | {_fmt(s.shortfall_bps['mean'])}/"
            f"{_fmt(s.shortfall_bps['p50'])}/{_fmt(s.shortfall_bps['p95'])}/"
            f"{_fmt(s.shortfall_bps['max'])} |"
        )
    return lines


