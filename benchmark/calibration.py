"""Profile calibration helpers (WHI-1447 / I21; docs/DESIGN.md §2.12: "Profile
calibration fixes representative daily corpus/budgets before the final comparison";
`graph.chunks` is "swept alongside percentage granularity").

Two small, offline pieces:

- `sweep_profiles` materializes a declared parameter grid as ordinary schema-2 run
  profiles (one YAML per grid point, derived from a checked-in base profile). The
  generated files are checked in next to their base, so every calibration run replays
  from a file whose hash its manifest records; nothing is varied at run time.
- `summarize_runs` reads saved run records only (never re-solves) and reports, per
  (run, algorithm): the full-schedule status counts, per-case solve-time and quote-count
  distributions, and the gross shortfall against the **best known** gross output among
  all the given runs for the same case (a finite-grid comparison, not an optimum).

Calibration must run on the corpus's declared `tuning` split only (DESIGN §2.4); the
summary refuses runs whose bundles differ, so variants are only compared on identical
cases, liquidity and objective.
"""

from __future__ import annotations

import itertools
import math
from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from fractions import Fraction
from pathlib import Path
from typing import Any

import yaml

from benchmark.profile import GRAPH_KEYS, SEARCH_KEYS, ProfileError, parse_profile
from benchmark.results import ResultError, load_case_records, load_manifest

GENERATED_HEADER = (
    "# GENERATED by `main.py calibrate profiles` from {base} (WHI-1447 calibration sweep;\n"
    "# tuning split only, exploratory). Do not edit: regenerate from the base profile.\n"
    "# Grid point: {point}\n"
)


class CalibrationError(ValueError):
    """A sweep or summary request is inconsistent."""


def parse_grid(items: Sequence[str]) -> dict[str, list[int]]:
    """`["percent_step=10,5", "chunks=20,40"]` -> ordered integer axes. Keys are the
    profile's `search.*`/`graph.*` names."""
    grid: dict[str, list[int]] = {}
    for item in items:
        key, sep, values = item.partition("=")
        key = key.strip()
        if not sep or not values.strip():
            raise CalibrationError(f"grid axis {item!r}: expected key=v1,v2,...")
        if key not in SEARCH_KEYS and key not in GRAPH_KEYS:
            raise CalibrationError(
                f"grid axis {key!r}: not a search/graph key "
                f"({sorted(SEARCH_KEYS) + sorted(GRAPH_KEYS)})"
            )
        if key in grid:
            raise CalibrationError(f"grid axis {key!r}: declared twice")
        try:
            axis = [int(v) for v in values.split(",")]
        except ValueError as exc:
            raise CalibrationError(f"grid axis {item!r}: integers only") from exc
        if len(set(axis)) != len(axis):
            raise CalibrationError(f"grid axis {item!r}: duplicate values")
        grid[key] = axis
    if not grid:
        raise CalibrationError("empty grid")
    return grid


def sweep_profiles(
    base_path: str | Path,
    grid: Mapping[str, Sequence[int]],
    *,
    algorithms: Sequence[str] | None = None,
    prefix: str = "sweep",
) -> dict[str, str]:
    """`{file name: YAML text}` for every grid point of `grid` applied to the base
    profile (optionally with a narrower algorithm list). Every generated profile is
    validated with the ordinary loader before it is returned."""
    base_path = Path(base_path)
    raw = yaml.safe_load(base_path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise CalibrationError(f"{base_path}: not a mapping")
    keys = list(grid)
    out: dict[str, str] = {}
    for values in itertools.product(*(grid[k] for k in keys)):
        doc = yaml.safe_load(yaml.safe_dump(raw, sort_keys=False))  # deep copy
        if algorithms is not None:
            doc["algorithms"] = list(algorithms)
        point = dict(zip(keys, values, strict=True))
        for key, value in point.items():
            section = "search" if key in SEARCH_KEYS else "graph"
            doc.setdefault(section, {})[key] = value
        try:
            parse_profile(doc, "<generated>")
        except ProfileError as exc:
            raise CalibrationError(f"grid point {point}: {exc}") from exc
        name = prefix + "".join(f"-{k.replace('_', '')}{v}" for k, v in point.items()) + ".yaml"
        header = GENERATED_HEADER.format(
            base=base_path.as_posix(),
            point=", ".join(f"{k}={v}" for k, v in point.items()),
        )
        out[name] = header + yaml.safe_dump(doc, sort_keys=False)
    return out


